function OrderManager.consumeOrder(userId, subKey)
    local removes = {}
    for orderId, order in pairs(Orders) do
        if order.userId == userId and order.subKey == subKey then
            EngineUtil.disposePlatformOrder(userId, orderId, true)
            table.insert(removes, orderId)
        end
    end
    for _, orderId in pairs(removes) do
        Orders[orderId] = nil
    end
    if PlayerManager:getPlayerByUserId(userId) == nil then
