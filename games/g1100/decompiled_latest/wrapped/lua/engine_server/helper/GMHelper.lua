function GMHelper:createPidPacketMapping()
    local path = FileUtil:getSettingPath() .. "C2SPidPacket.ini"
    local file = io.open(path, "r")
    local mapping = {}
    local result = {}
    if file then
        local content = file:read("*a")
        file:close()
        local lines = StringUtil.split(content, "\n")
        for _, line in pairs(lines) do
            local info = StringUtil.split(line, "=")
            mapping[info[1]] = tonumber(info[2])
            table.insert(result, line)
        end
    end
    ---@type SPacketHandlers
    local PacketHandlers = T(Global, "PacketHandlers")
    for key, _ in pairs(mapping) do
        if not PacketHandlers[key] then
            mapping[key] = nil
        end
    end
    local function getAvailableId()
        local maxId = 0
        for _, hashId in pairs(mapping) do
            if maxId < hashId then
                maxId = hashId
            end
        end
        return maxId + 1
    end
    for key, value in pairs(PacketHandlers) do
        if type(value) == "function" and not mapping[key] then
            mapping[key] = getAvailableId()
            table.insert(result, key .. "=" .. mapping[key])
        end
    end
    file = io.open(path, "w")
    file:write(table.concat(result, "\n"))
    file:close()
end

