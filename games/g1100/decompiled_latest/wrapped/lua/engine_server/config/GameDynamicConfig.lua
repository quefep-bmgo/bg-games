function GameDynamicConfig:isInGrayscale(name, userId)
    local key = DBManager:getGameType() .. "_" .. name
    local value = self.config.grayscale[key]
    if not value then
        return false
    end
    if type(value) == "number" then
        return (userId % 100) + 1 <= value
    elseif type(value) == "table" then
        return TableUtil.tableContain(value, userId)
    else
        return false
    end
end

function GameDynamicConfig:isCanEnterGame()
    local gameType = DBManager:getGameType()
    local value = self.config.minEngineVersion[gameType]
    if type(value) ~= "number" then
        return true
    end
    return EngineVersionSetting.getEngineVersion() >= value
end

