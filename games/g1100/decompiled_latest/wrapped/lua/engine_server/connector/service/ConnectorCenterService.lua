function ConnectorCenterService:sendPlayerCount(logoutId)
    local playerCount = 0
    local aiCount = 0
    local players = PlayerManager:getPlayers()
    for _, player in pairs(players) do
        if player.userId ~= logoutId then
            if PlayerManager:isAIPlayer(player) then
                aiCount = aiCount + 1
            else
                playerCount = playerCount + 1
            end
        end
    end
    local data = {
        gameType = GameType,
        gameId = GameServer:getServerConfig().gameId,
        playerCount = playerCount,
        aiCount = aiCount
    }
    data = json.encode(data)
    LogUtil.logInfo("[ConnectorCenterService:sendPlayerCount]", data)
    ConnectorCenter:sendMsg(Game2ConnectorMsgType.PlayerCount, 0, data)
end

