local SConnectorDispatch = class("SConnectorDispatch", require "engine_base.connector.IConnectorDispatch")

---@protected
---@param type number 消息类型
---@param targets number[] 接收者userId列表
---@param data table | string 接收数据
function SConnectorDispatch:onMsgReceive(type, targets, data)
    local intercept = self.super.onMsgReceive(self, type, targets, data)
    if intercept then
        ---服务器拦截了该消息，不发送给客户端
        return
    end
    local builder = DataBuilder.new()
    builder:addParam("type", type)
    if data and #data > 0 then
        builder:addParam("data", data)
    end
    local result = builder:getListData()
    if #targets == 0 or tostring(targets[1]) == "0" then
        PacketSender:broadCastLuaCommonData("ConnectorMsg", result)
    else
        for _, userId in pairs(targets) do
            local player = PlayerManager:getPlayerByUserId(userId)
            if player then
                PacketSender:sendLuaCommonData(player.rakssid, "ConnectorMsg", result)
            end
        end
    end
end

