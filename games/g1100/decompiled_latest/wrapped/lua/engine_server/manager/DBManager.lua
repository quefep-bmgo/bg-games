function DBManager:saveAllDataCache()
    if #WaitSaveCache == 0 then
        return
    end
    local total = 0
    local body = {}
    local function findCache()
        local locks = {}
        local find = true
        while find do
            local iFind = false
            for pos, cache in pairs(WaitSaveCache) do
                if not PushCacheLock[cache.key] then
                    if total < DEFAULT_PUSH_SIZE then
                        iFind = true
                        locks[cache.key] = true
                        total = total + cache.size
                        TotalCacheSize = TotalCacheSize - cache.size
                        table.insert(body, cache.data)
                        table.remove(WaitSaveCache, pos)
                        break
                    end
                end
            end
            find = iFind
        end
        for key, _ in pairs(locks) do
            PushCacheLock[key] = true
        end
        return total > 0
    end
    while findCache() do
        for _, item in pairs(body) do
            LogUtil.logInfo("[DBManager][1] save player data, userId=" .. item.userId .. ", subKey=" .. item.subKey)
        end
        saveGameData(TableUtil.copyTable(body), json.encode(body))
        total = 0
        body = {}
    end
    PushCacheTime = os.time()
end

---@param player SBasePlayer
function DBManager:savePlayerDataCache(player)
    local removes = {}
    local hasLockCache = false
    local userId = tostring(player.userId)
    for _, cache in pairs(WaitSaveCache) do
        if cache.data.userId == userId then
            if PushCacheLock[cache.key] then
                hasLockCache = true
            else
                table.insert(removes, cache)
            end
        end
    end
    local body = {}
    for _, cache in pairs(removes) do
        PushCacheLock[cache.key] = true
        TotalCacheSize = TotalCacheSize - cache.size
        table.insert(body, cache.data)
        TableUtil.tableRemove(WaitSaveCache, cache)
    end
    if next(body) then
        for _, item in pairs(body) do
            LogUtil.logInfo("[DBManager][3] save player data, userId=" .. item.userId .. ", subKey=" .. item.subKey)
        end
        saveGameData(TableUtil.copyTable(body), json.encode(body))
        OrderManager.reportBilling(player.userId)
        OrderManager.reportCashBillings(player.userId)
    end
    if hasLockCache then
        ---当前有正在Http存储中被锁住的缓存，需要在1秒后重试
        LuaTimer:schedule(function()
            DBManager:savePlayerDataCache(player)
        end, 1000)
    end
end

