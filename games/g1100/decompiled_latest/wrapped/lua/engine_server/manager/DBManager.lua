    if subKey then
        local key = tostring(userId) .. "#" .. subKey
        for _, cache in pairs(WaitSaveCache) do
            if cache.key == key then
                return true
            end
        end
        for _key, _ in pairs(PushCacheLock) do
            if _key == key then
                return true
            end
        end
        return false
    else
        userId = tostring(userId)
        for _, cache in pairs(WaitSaveCache) do
            if StringUtil.split(cache.key, "#")[1] == userId then
                return true
            end
        end
        for key, _ in pairs(PushCacheLock) do
            if StringUtil.split(key, "#")[1] == userId then
                return true
            end
        end
        return false
    end
end

function DBManager:hasAnyDataSaving()
    if next(WaitSaveCache) ~= nil then
        return true
    end
    if next(PushCacheLock) ~= nil then
        return true
    end
    return false
end

function DBManager:isPlayerLoadFailed(userId)
    return InitDataFailedRecord[tostring(userId)]
end

function DBManager:isEnableDB()
    return PlayerDBSaveFunction ~= nil
end

function DBManager:isPlayerDBReady(userId)
    return isPlayerDBReady(userId)
end

function DBManager:listenerDataSaveEnd(userId, subKey, callback)
    if self:hasDataSaving(userId, subKey) then
        LuaTimer:scheduleTicker(function()
            self:listenerDataSaveEnd(userId, subKey, callback)
        end, 1, 1)
    else
        if PlayerManager:getPlayerByUserId(userId) then
            callback()
        end
    end
end

