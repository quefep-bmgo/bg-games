---@class UIGMMain : IGUILayout
local UIGMMain = class("GUIGMMain", IGUILayout)

local IsOpenEventDialog = false
local EventList = {}

function UIGMMain:isAlwaysShow()
    return true
end

function UIGMMain:onLoad()
    self.root:SetLevel(2)
    self.btnOpen = self:getChildWindow("GMMain-Open", GUIType.Button)
    self.btnOpen:registerEvent(GUIEvent.ButtonClick, function()
        GUIGMControlPanel:show()
    end)
end

function UIGMMain:setTransparent()
    self.btnOpen:SetPushedImage("")
    self.btnOpen:SetNormalImage("")
end

function UIGMMain:changeOpenEventDialog(isOpen)
    IsOpenEventDialog = isOpen
    if not IsOpenEventDialog then
        EventList = {}
    end
    ClientHelper.putBoolForKey("g1008_isOpenEventDialog", isOpen)
end

function UIGMMain:addEventToDialog(event_map)
    if IsOpenEventDialog then
        table.insert(EventList, event_map)
    end
end

function UIGMMain:onTick()
    if not IsOpenEventDialog or CustomDialog.isShow() then
        return
    end
    local event_map = EventList[1]
    if not event_map then
        return
    end
    local title = "埋点" .. event_map.event
    event_map.event = nil
    local text = ""
    for key, value in pairs(event_map) do
        text = text .. TextFormat.colorRed .. key .. TextFormat.colorWrite .. " : " .. TextFormat.colorBlack .. tostring(value) .. "\n"
    end
    CustomDialog.builder()
                .setTitleText(title)
                .setContentText(text)
                .show()
    table.remove(EventList, 1)
end

