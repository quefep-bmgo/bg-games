function UIHelper.onSetImageUrl(imageWnd, url)
    -- if string.match(url, "http.*") then
    -- 	url = url .. "?pendant=pendant_test.json"
    -- end
    local havePendant = false
    local picPath, params = string.match(url, "([^?]*)(.*)")
    if not Global.setting.disableHeadImagePendant and params ~= "" then
        local pendant = string.match(params, ".*%?pendant=([^?]+)")
        if pendant then
            Plugins.CallTargetPluginFunc("new_vip", "setHeadImagePendant", imageWnd, pendant, true)
            havePendant = true
        end
    end
    if not havePendant then
        local name = imageWnd:GetName() .. "_pendant"
        local pendant = GUIManager:getWindowByName(name, GUIType.DynamicImage)
        if pendant then
            pendant:SetVisible(false)
        end
    end
    return picPath
end

function onSetImageUrl(imageWnd, url)
    return UIHelper.onSetImageUrl(imageWnd, url)
