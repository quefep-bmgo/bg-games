function IGUIListView:ctor(name, parent, root, orientation)
    if not parent then
        return
    end
    if not root then
        orientation = orientation or Orientation.Vertical
        if orientation == Orientation.Vertical then
            root = GUIManager:createGUIWindow(GUIType.List, name)
        else
            root = GUIManager:createGUIWindow(GUIType.ListHorizontal, name)
        end
        root:SetArea({ 0, 0 }, { 0, 0 }, { 1, 0 }, { 1, 0 })
    end
    self:init(root)
    self.orientation = orientation
    parent:AddChildWindow(self.root)
end

