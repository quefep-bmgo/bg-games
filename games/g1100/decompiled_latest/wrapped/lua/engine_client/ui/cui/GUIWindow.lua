function GUIWindow:SetTextAutoFont(text, defFont, minFont)
    self:SetText(text)
    self:SetProperty("Font", defFont)
    local width = self:GetPixelSize().x
    local font = math.floor(string.gsub(defFont, "%D", ""))
    local type = string.gsub(defFont, font, "")
    minFont = minFont or 8
    while self:GetTextWidth() > width do
        font = font - 2
        self:SetProperty("Font", type .. font)
        if font <= minFont then
            break
        end
    end
