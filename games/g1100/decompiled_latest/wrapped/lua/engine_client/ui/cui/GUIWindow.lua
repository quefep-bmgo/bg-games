function GUIWindow:GetTextHeight()
    local texts = StringUtil.split(self:GetText(), '\n', true)
    local width = self:GetPixelSize().x
    local lines = 0
    local heights = 0
    local space = self.GetTextLineExtraSpace ~= nil and self:GetTextLineExtraSpace() or 0
    for _, text in pairs(texts) do
        lines = lines + math.floor(self:GetFont():GetTextExtent(text, 1) / width) + 1
        if text == "" then
            text = " "
        end
        heights = heights + self:GetFont():GetTextTotalHigh(width, text)
    end
    return heights + space * lines
end

function GUIWindow:GetTextWidth()
    return self:GetFont():GetTextExtent(self:GetText(), 1)
end

