function GameAnalytics:getEventBlacklist()
    self.eventBlacklist = {}
    WebService:getEngineEventBlacklist(function(data, code)
        if code == 1 then
            local commonData = data["common"]
            local gameData = data[BaseMain:getGameType()]
            if commonData ~= nil and next(commonData) then
                for _, v in pairs(commonData) do
                    self.eventBlacklist[v] = true
                end
            end
            if gameData ~= nil and next(gameData) then
                for _, v in pairs(gameData) do
                    self.eventBlacklist[v] = true
                end
            end
        else
            print("[Lua] GameAnalytics:getEventBlacklist error: code = ", code)
        end
    end)
end

