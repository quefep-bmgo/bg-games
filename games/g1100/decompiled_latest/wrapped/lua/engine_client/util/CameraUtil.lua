---起始点到目标点的yaw和pitch值
---@param fromPos Vector3
---@param targetPos Vector3
function CameraUtil.getPitchAndYaw(fromPos, targetPos)
    local vector = math.atan2(targetPos.x - fromPos.x, targetPos.z - fromPos.z)
    local yaw = vector / math.pi * -180

    local dir = VectorUtil.sub3(targetPos, fromPos)
    local pitch = MathUtil.GetVector3Angle(VectorUtil.newVector3(dir.x, 1, dir.z), dir)

    return yaw, pitch
end

