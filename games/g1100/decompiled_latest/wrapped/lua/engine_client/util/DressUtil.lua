local function parseResourceId(resourceId, unload, typeId, signature, color, dyeColors)
    if typeId and typeId == 6 then
        local resource = StringUtil.split(resourceId, "-", false, true)
        if #resource == 4 then
            return { color = { resource[1] / 255, resource[2] / 255, resource[3] / 255, resource[4] / 255 } }
        end
    else
        local resource = StringUtil.split(resourceId, ".")
        return { master = resource[1], slave = resource[2] or "", unload = unload, signature = signature, color = color, dyeColors = dyeColors }
    end
end

function DressUtil:parseDressData(data)
    local skins = {}
    for _, item in pairs(data or {}) do
        ---@type PartSkin
        local skin = parseResourceId(item.resourceId, false, item.typeId, item.signature, item.signatureColor, item.dyeDressingColor)
        if item.occupyPosition then
