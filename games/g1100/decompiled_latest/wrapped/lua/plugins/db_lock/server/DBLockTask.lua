---@private
---判断玩家是否持有db锁
function DBLockTask:hasLock(userId)
    if not GameDynamicConfig:isInGrayscale("db_lock", userId) then
        return true
    end
    if isLocalDb() or not DBManager:isEnableDB() then
        return true
    end
    return LockTasks[userId] ~= nil
end

---申请db锁
---@param player SBasePlayer
function DBLockTask:applyLock(player, retryTimes)
    if not player then
        return
    end
    if not GameDynamicConfig:isInGrayscale("db_lock", player.userId) then
        return
    end
    if isLocalDb() or not DBManager:isEnableDB() then
        return
    end
    local userId = player.userId
    player.isKickOut = true
    retryTimes = retryTimes or 2
    self:updateLock(userId, function(failed)
        if not failed then
            return
        end
        if retryTimes == 0 then
            HostApi.sendGameoverByPlatformUserId(userId, "system.message.kick.user.out.duplicate.enter", GameOverCode.GameOver)
            LogUtil.logWarning("[DBLockTask] applyLock failed. userId=" .. userId)
        else
            LuaTimer:schedule(function()
                self:applyLock(PlayerManager:getPlayerByUserId(userId), retryTimes - 1)
            end, 1500)
        end
    end)
end

---@private
---续约db锁
function DBLockTask:updateLock(userId, callback)
    WebService:UpdateDBLock(userId, function(data)
        local isKickOut = false
        if not data or data.lock ~= 1 then
            isKickOut = true
        else
            LockTasks[userId] = {
                userId = userId,
                checkTime = os.time(),
                expireTime = math.floor(data.expireTime / 1000) - 1,
            }
            LogUtil.logInfo("[DBLockTask] updateLock success. userId=" .. userId)
        end
        local player = PlayerManager:getPlayerByUserId(userId)
        if player then
            player.isKickOut = isKickOut or player.isKickOutDB
            if not player.isKickOutDB then
                callback(isKickOut)
            end
        else
            if self:hasLock(userId) and not TableUtil.tableContain(ReleaseTasks, userId) then
                table.insert(ReleaseTasks, userId)
            end
        end
    end)
end

---@param player SBasePlayer
function DBLockTask:releaseLock(player)
    if not self:hasLock(player.userId) then
        return
    end
    if not TableUtil.tableContain(ReleaseTasks, player.userId) then
        table.insert(ReleaseTasks, player.userId)
    end
end

---@private
function DBLockTask:onTick()
    self:checkUpdateLock()
    self:checkReleaseLock()
end

---@private
---检测db锁是否需要续约
---每隔30秒续约一个60秒的db锁，保证当前服务器持续持有锁，其他服务器无法修改数据
function DBLockTask:checkUpdateLock()
    local time = os.time()
    for _, lock in pairs(LockTasks) do
        if time - lock.checkTime >= 30 then
            lock.checkTime = time
            self:updateLock(lock.userId, function(failed)
                if failed then
                    local player = PlayerManager:getPlayerByUserId(lock.userId)
                    if player then
                        ---续约失败，及时保存数据，并踢出玩家，不允许玩家执行任何操作
                        DBManager:callSavePlayerData(player)
                        HostApi.sendGameover(player.rakssid, IMessages:msgGameOverByDBDataError(), GameOverCode.LoadDBDataError)
                        LogUtil.logWarning("[DBLockTask] updateLock failed. userId=" .. player.userId)
                    end
                end
            end)
        end
    end
end

---@private
---检测释放锁
function DBLockTask:checkReleaseLock()
    local releases = {}
    for _, userId in pairs(ReleaseTasks) do
        if not DBManager:hasDataSaving(userId) then
            table.insert(releases, userId)
        end
    end
    if next(releases) == nil then
        return
    end
    for _, userId in pairs(releases) do
        local player = PlayerManager:getPlayerByUserId(userId)
        ---玩家不存在才能释放锁
        if not player then
            local lock = LockTasks[userId]
            TableUtil.tableRemove(ReleaseTasks, userId)
            if lock then
                WebService:ReleaseDBLock(userId)
                LogUtil.logInfo("[DBLockTask] releaseLock. userId=" .. userId)
            end
            LockTasks[userId] = nil ---释放锁
        end
    end
end

