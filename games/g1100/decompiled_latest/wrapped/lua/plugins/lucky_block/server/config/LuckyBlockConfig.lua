function LuckyBlockConfig:init()
    local blockConfig = FileUtil.getGameConfigFromCsv("lucky_block/BlockSetting.csv")
    for i, v in pairs(blockConfig) do
        ---@class LuckyBlock
        local item = {}
        item.id = tonumber(v.id)
        item.poolId = v.poolId
        item.blockId = v.blockId
        LuckyBlocks[item.blockId] = item
    end

    local poolConfig = FileUtil.getGameConfigFromCsv("lucky_block/BlockGoodsPool.csv")
    for _, config in pairs(poolConfig) do
        ---@class LuckyBlockPoolItem
        local item = {}
        item.id = tonumber(config.id)
        item.itemId = tonumber(config.itemId)
        item.itemMeta = tonumber(config.itemMeta) or 0
        item.poolId = tonumber(config.poolId) or 0
