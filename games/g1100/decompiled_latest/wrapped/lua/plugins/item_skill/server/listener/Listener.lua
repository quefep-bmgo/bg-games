functionMap["ItemSkillSpHandleEvent"] = function(entityId, itemId, position)
    local player = PlayerManager:getPlayerByEntityId(entityId)
    if not player then
        return false
    end
    local skill = SkillConfig:getSkill(itemId)
    if not skill then
        return false
    end
    if not player.isLife then
        return false
    end
    return true
end

