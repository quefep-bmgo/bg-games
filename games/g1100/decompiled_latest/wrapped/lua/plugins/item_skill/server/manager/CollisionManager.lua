}

function CollisionManager:addCollision(entityId, position, type, needArea, teamId, userId)
    local Collision = Plugins.Require("item_skill", "server.entity.mount.Collision")
    local collision = Collision.new(entityId, position, type,
            needArea or false, teamId or 0, userId or 0)
    Collisions[tostring(entityId)] = collision
end

function CollisionManager:removeCollision(entityId)
    if Collisions[tostring(entityId)] ~= nil then
        Collisions[tostring(entityId)] = nil
    end
end

function CollisionManager:checkCollision(ticks)
    for _, collision in pairs(Collisions) do
        if collision ~= nil then
            collision:checkCollisionArea(ticks)
        end
    end
end

function CollisionManager:getCollisionRangeByType(type)
    local range = CollisionRange[type]
    if range == nil then
        range = CollisionRange[self.CollisionType.Block]
    end
    return range
end

