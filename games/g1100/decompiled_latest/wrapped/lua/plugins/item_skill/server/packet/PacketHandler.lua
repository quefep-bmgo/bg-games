function PacketHandlers.OnAttackEntity(self, packet)
    local entityId = packet.entityId
    local monster = MonsterManager:getMonster(entityId)
    if monster and monster.onAttacked and self.getCurAttackDamage then
        if monster:onAttacked(self, self:getCurAttackDamage()) then
            local inv = self:getInventory()
            local ItemStack = inv:getCurrentItem()
