function handlers.onPlayerLogout(player)
    local userId = player.userId
    LuaTimer:schedule(function()
        if PlayerManager:getPlayerByUserId(userId) then
            return
        end
        ReportValue.removeReportValueData(userId)
    end, 60000)
end

