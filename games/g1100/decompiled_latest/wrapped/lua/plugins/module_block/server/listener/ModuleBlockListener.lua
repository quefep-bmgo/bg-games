function ModuleBlockListener.onBlockPlace(rakssid, itemId, itemMeta, toPlacePos)
    ---@type SBasePlayer
    local player = PlayerManager:getPlayerByRakssid(rakssid)
    if not player then
        return
    end
    local key = player.userId .. ":" .. itemId
    local moduleId = PlayerModuleBlockRecord[key] or ModuleBlockConfig:getDefaultModuleId(itemId)
    if moduleId == 0 then
        return
    end
    local setting = ModuleBlockConfig:getModuleBlock(itemId, moduleId, player.teamId)
    if not setting then
        return
    end
    if not string.find(setting.schematic, ".schematic") then
        return
    end
    if player:getItemNumById(itemId, itemMeta) < setting.consumeNum then
        player:sendPacket({
            pid = "showToast",
            content = "plugins.module.lack.block",
            time = 2000
        })
        return false, true
    end
    local yaw, reversalX, reversalZ = player:getYaw() % 360, false, false
    if yaw < 0 then
        yaw = yaw + 360
    end
    if yaw >= 45 and yaw < 135 then
        yaw, reversalX, reversalZ = 90, true, false
    elseif yaw >= 135 and yaw < 225 then
        yaw, reversalX, reversalZ = 180, true, true
    elseif yaw >= 225 and yaw < 315 then
        yaw, reversalX, reversalZ = 270, false, true
    else
        yaw, reversalX, reversalZ = 0, false, false
    end
    local startPos = MathUtil.getForwardPos(toPlacePos, yaw, setting.offsetX)
    startPos = MathUtil.getLeftPos(startPos, yaw, setting.offsetZ)
    EngineWorld:createSchematic(setting.schematic, startPos, reversalX, reversalZ, false, rakssid, 0, 1, setting.extraParam)
    player:removeItem(itemId, setting.consumeNum, itemMeta)
    return false, true
end

