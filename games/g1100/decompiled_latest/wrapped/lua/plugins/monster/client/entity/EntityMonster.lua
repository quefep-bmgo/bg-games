function EntityMonster:showDamageFloatText(damage, color)
    local position = self.entity:getPosition()
    local actor = self.cfg.actorName
    local width = 0.7
    local height = 1.8
    local size = ActorSizeSetting.getActorSize(actor)
    if size then
        width = math.min(2.5, size.width * 0.7)
        height = math.min(1.8, size.height)
    end
    position.y = position.y + height + self.damageOffset
    if not color then
        color = 1
        if self.isCrit then
            color = 2
            self.isCrit = nil
        elseif self.isEffectHurt then
            color = 3
            self.isEffectHurt = nil
        end
    end
    local playerPos = PlayerManager:getClientPlayer():getPosition()
    if VectorUtil.distance(playerPos, position) <= 80 then
        WorldImageRender.Instance():addFloatNumber(damage, position, width, color)
        self.damageOffset = 0.3 * math.max(width, 1)
    end
end

