function GMHelper:addMonsterDropWeight(_, multi)
    ---@type MonsterRewardConfig
    local MonsterRewardConfig = T(Global, "MonsterRewardConfig")
    local cfgs = MonsterRewardConfig:getAllCfgs()
    for _, group in pairs(cfgs) do
        for _, reward in pairs(group) do
            reward[4] = reward[4] * multi
        end
    end
    ---@type MonsterBossRewardConfig
    local MonsterBossRewardConfig = T(Global, "MonsterBossRewardConfig")
    cfgs = MonsterBossRewardConfig:getAllCfgs()
    for _, monster in pairs(cfgs) do
        for _, rewards in pairs(monster) do
            for _, reward in pairs(rewards) do
                reward[3] = reward[3] * multi
            end
        end
    end
end

