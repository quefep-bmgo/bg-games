function SResources:onTick(ticks)
    if self.info.item[1] == 0 then
        return
    end
    if self.itemCount >= self.info.max then
        return
    end
    if ticks % self.info.interval == 0 then
        local item = self.info.item
        self.itemCount = self.itemCount + 1
        local posOffset = PosOffset[self.itemCount]
        local pos = VectorUtil.newVector3(self.itemPos.x + posOffset.x, self.itemPos.y, self.itemPos.z + posOffset.z)
        local entityId = EngineWorld:addEntityItem(item[1], 1, item[2], 99999, pos)
        self.items[tostring(entityId)] = true
    end
end

