function ShopPkHandler:onPlayerRecycleShop(packet)
    local customGame = T(Global, "customGame")
    if not customGame:checkOwner(self.userId) and self:getPermissionRole() ~= Define.CustomGamePermissionRole.Admin then
        return
    end
    if not self:checkCanAddItem(Define.NpcItemId, 0, 1) then
        PidPacketSender:sendShopTip(self.userId, "gui.shop.is.full.inventory")
