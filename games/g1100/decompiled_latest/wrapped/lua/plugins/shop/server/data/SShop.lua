function SShop:onBuyGoods(userId, goods)
    local player = PlayerManager:getPlayerByUserId(userId)
    if not player then
        return
    end
    local canBuy = false
    for _, list in pairs(self.goods) do
        for i, str in pairs(list.goods) do
            if goods == str then
                canBuy = true
                break
            end
        end
    end
    if canBuy then
        local tb = StringUtil.split(goods, ":", false, true)
        if not ItemsConfig:checkGoodsInfoEnable(tb[1], tb[2])
                or not ItemsConfig:checkGoodsInfoEnable(tb[4], tb[5])
                or tb[3] <= 0 or tb[6] < 0 then
            return
        end
        if player:getItemCount(tb[4], tb[5]) < tb[6] then
            PidPacketSender:sendShopTip(player.userId, "gui.shop.no.enough.item")
            return
        end
        if not player:checkCanAddItem(tb[1], tb[2], tb[3]) then
            PidPacketSender:sendShopTip(player.userId, "gui.shop.is.full.inventory")
            return
        end

        player:removeItem(tb[4], tb[6], tb[5])
        player:addItem(tb[1], tb[3], tb[2])
        HostApi.notifyGetItem(player.rakssid, tb[1], tb[2], tb[3])
    end
end

