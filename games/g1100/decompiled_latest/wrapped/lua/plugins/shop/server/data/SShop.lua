function SShop:saveShop(goodsInfo, name)
    self.name = name
    local goods = {}
    for _, info in pairs(goodsInfo) do
        if #goods < Define.ShopTabMax and info.tab and info.goods and not TableUtil.isEmpty(info.goods) then
            for i = #info.goods, 1, -1 do
                local tb = StringUtil.split(info.goods[i], ":", false, true)
                if not ItemsConfig:checkGoodsInfoEnable(tb[1], tb[2])
                        or not ItemsConfig:checkGoodsInfoEnable(tb[4], tb[5])
                        or tb[3] <= 0 or tb[6] < 0 then
                    table.remove(info.goods, i)
                end
            end
            if #info.goods > 0 then
                table.insert(goods, {
                    tab = info.tab,
                    goods = info.goods
                })
            end
        end
        if #goods == Define.ShopTabMax then
            break
        end
    end
    self.goods = goods
    local syncData = {}
    syncData[self.id] = self:getSyncInfo()
    PacketSender:broadCastPidPacket({
        pid = "syncShop",
        data = syncData
