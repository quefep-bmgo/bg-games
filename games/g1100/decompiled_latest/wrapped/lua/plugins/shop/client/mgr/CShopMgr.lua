---@type CShop
local Shop = Plugins.Require("shop", "client.data.CShop")
---@type [string, CShop]
local Shops = {}
---@type UICustomShopLayout
local GUICustomShop = UIHelper.newGameGUILayout("GUICustomShop")

function CShopMgr:syncShopInfo(data)
    for id, info in pairs(data) do
        if Shops[id] then
            local shop = Shops[id]
            shop:updateShop(info)
        else
            if TableUtil.getTableSize(Shops) >= Define.ShopMax then
                return
            end
            local shop = Shop.new(id, info)
            if shop then
                Shops[id] = shop
            end
        end
    end
end

function CShopMgr:removeShop(id)
    Shops[tostring(id)] = nil
    if GUICustomShop:isShow() and GUICustomShop.shopId and GUICustomShop.shopId == id then
        GUICustomShop:hide()
    end
end

---@return CShop
function CShopMgr:getShop(id)
    return Shops[id]
end

function CShopMgr:getShopIdByEntityId(entityId)
    for id, shop in pairs(Shops) do
        if shop:checkEntityId(entityId) then
            return id
        end
    end
    return false
end

