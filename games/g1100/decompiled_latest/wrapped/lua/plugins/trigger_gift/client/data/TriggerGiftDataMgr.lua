function TriggerGiftDataMgr:removeTriggerGiftData(giftId)
    for index, gift in pairs(TriggerGiftData) do
        if gift.giftId == giftId then
            table.remove(TriggerGiftData, index)
        end
    end
    self:showTriggerGiftWindow()
end

function TriggerGiftDataMgr:addTriggerGiftData(data)
    for _, gift in pairs(data) do
        table.insert(TriggerGiftData, 1, gift)
    end
    self:showCountDown()
    self:showTriggerGiftWindow()
    if #TriggerGiftData > 0 then
        self.triggerGiftLayout:changeCurSelect(1)
    end
end

function TriggerGiftDataMgr:checkTriggerGiftData()
    for i = #TriggerGiftData, 1, -1 do
        local data = TriggerGiftData[i]
        local config = TriggerGiftDescConfig:getCfgById(data.giftId)
        if not config or ( TriggerGiftData[i].startTime + config.duration <= os.time() )then
            table.remove(TriggerGiftData, i)
        end
    end
end

