function TriggerGiftDataMgr:showCountDown()
    if not self.stCountDown then
        return
    end
    local latestTime = 0

    for _, data in pairs(TriggerGiftData) do
        local config = TriggerGiftDescConfig:getCfgById(data.giftId)
        local lastTime = data.startTime + config.duration - os.time()
        if lastTime > latestTime then
            latestTime = lastTime
        end
    end

    LuaTimer:cancel(self.countDownKey)
    self.stCountDown:SetVisible(false)
    if latestTime > 0 then
        self.stCountDown:SetVisible(true)
        self.countDownKey = LuaTimer:scheduleTimer(function()
            latestTime = latestTime - 1
            if latestTime == 0 then
                self.stCountDown:SetVisible(false)
                self:showTriggerGiftWindow()
            else
                self.stCountDown:SetText(DateUtil.getFormatTime(latestTime))
            end
        end, 1000, latestTime)
    end
end

