local TriggerGiftActivityConfig = Plugins.Require("trigger_gift", "common.config.TriggerGiftActivityConfig")
---@type TriggerGiftTriggerListConfig
local TriggerGiftTriggerListConfig = Plugins.Require("trigger_gift", "common.config.TriggerGiftTriggerListConfig")

local activeList = {}

function TriggerGiftActivityMgr:init()
    EventUtil.goObjEvent(self)
    activeList = {}

    self:checkActiveActivity()
end

function TriggerGiftActivityMgr:isActiveActivity(activityId)
    return activeList[activityId]
end

function TriggerGiftActivityMgr:checkActiveActivity()
    local currTime = os.time()
    local configList = TriggerGiftActivityConfig:getAllCfg()

    local nextCheckTime = math.maxinteger
    for activityId, config in pairs(configList) do
        if currTime >= config.startDate and currTime <= config.endDate and not activeList[activityId] then
            --- 添加
            activeList[activityId] = true
            self:emitEvent("activeActivity", activityId)
            nextCheckTime = math.min(nextCheckTime, config.endDate + 1)
        elseif currTime < config.startDate then
            nextCheckTime = math.min(nextCheckTime, config.startDate)
        elseif currTime > config.endDate and activeList[activityId] then
            --- 移除
            activeList[activityId] = nil
            self:emitEvent("disActiveActivity", activityId)
        end
    end

    LuaTimer:scheduleTimer(function()
        self:checkActiveActivity()
    end, (nextCheckTime - currTime) * 1000, 1)
end

function TriggerGiftActivityMgr:getAllActiveGift()
    local allConfig = {}
    for activityId, _ in pairs(activeList) do
        local configList = TriggerGiftTriggerListConfig:getCfgListByActivityId(activityId)
        TableUtil.appendArray(allConfig, configList)
    end

    return allConfig
end

