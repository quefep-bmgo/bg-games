function TriggerGiftMgr:onPlayerBuyTriggerGift(giftId)
    local player = PlayerManager:getPlayerByUserId(self.userId)
    if not player then
        return
    end

    if not self.TriggerGiftCache.giftRecord[giftId] then
        return
    end

    local config = TriggerGiftDescConfig:getCfgById(giftId)
    if os.time() > self.TriggerGiftCache.giftRecord[giftId].startTime + config.duration then
        self.TriggerGiftCache.giftRecord[giftId] = nil
        return
    end

    PayHelper.payMoneySync(player, giftId, CurrencyId.GCube, config.price, function()
        local rewards = TriggerGiftRewardGroupConfig:getCfgByGroupId(config.rewardGroupId) or {}
        local rewardIds = {}
        for _, reward in pairs(rewards) do
            rewardIds[tostring(reward.realId)] = reward.num
            Events.CommonReceiveRewardEvent:invoke(player, reward.type, reward.realId, reward.num, 0, reward.rewardId)
        end
        self.TriggerGiftCache.giftRecord[giftId] = nil
        if GameType == "g1008" or GameType == "g1046" or GameType == "g1061" or GameType == "g1062" or GameType == "g1065" then
            CommonPacketSender:sendShowReward(player.rakssid, rewardIds)
        end
        player:sendPacket({
            pid = "RemoveTriggerGift",
            giftId = giftId
        })
        GameAnalytics:newDesign(self.userId, "trigger_gift_buy", { giftId = tostring(giftId) })
    end)
end

local CHECK_GIFT_RECORD = {
    ---@param config TriggerGiftTriggerListData
    [Define.TriggerGiftKey.UseDiamonds] = function(player, cache, config)
        --- 在起始时间内
        if config.startDate then
            cache.accumulate = 0

            --- 平台查询累计消费
            local usedDiamonds = player:getUsedDiamondsByRecord(config.startDate)
            cache.accumulate = usedDiamonds

            if cache.accumulate >= config.param[1] and cache.accumulate <= config.param[2] then
                --- 标记触发时间
                cache.lastTriggerTime = os.time()
                --- 触发礼包
                player.triggerGiftMgr:activeTriggerGift(player, config.giftId)
            end
        end
    end,

    --- 每次登录大厅时检测
    ---@param config TriggerGiftTriggerListData
    [Define.TriggerGiftKey.UseMaxDiamonds] = function(player, cache, config)
        --- 平台查询最大消费
        local maxDiamond = player:getMaxDiamondConsumeByRecord(config.startDate)
        if maxDiamond >= config.param[1] and maxDiamond <= config.param[2] then
            --- 标记触发时间
            cache.lastTriggerTime = os.time()
            --- 触发礼包
            player.triggerGiftMgr:activeTriggerGift(player, config.giftId)
        end
    end,
}

function TriggerGiftMgr:checkTriggerGiftStatus()
    local player = PlayerManager:getPlayerByUserId(self.userId)
    if not player then
        return
    end

    for triggerId, cache in pairs(self.TriggerGiftCache.pushRecord) do
        local config = TriggerGiftTriggerListConfig:getCfgById(triggerId)
        --- 不存在配置 或 未激活状态
        if cache.lastTriggerTime == 0 and CHECK_GIFT_RECORD[config.trigger] then
            CHECK_GIFT_RECORD[config.trigger](player, cache, config)
        end
    end
end

