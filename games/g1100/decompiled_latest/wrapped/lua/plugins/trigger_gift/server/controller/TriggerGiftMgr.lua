function TriggerGiftMgr:activeActivity(activityId)
    local allConfig = TriggerGiftTriggerListConfig:getCfgListByActivityId(activityId)
    ---添加新增的触发式礼包
    for _, config in pairs(allConfig) do
        if not self.TriggerGiftCache.pushRecord[config.triggerId] then
            self.TriggerGiftCache.pushRecord[config.triggerId] = {
                triggerId = config.triggerId,
                lastTriggerTime = 0
