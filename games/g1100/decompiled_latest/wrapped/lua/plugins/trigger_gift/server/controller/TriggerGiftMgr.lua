local CHECK_GIFT_LIMIT = {
    [Define.TriggerGiftKey.Level] = function(cache, value)
        local config = TriggerGiftTriggerListConfig:getCfgById(cache.triggerId)
        --print("level ", value, config.param, type(value), type(config.param))
        return value >= config.param
    end,

    [Define.TriggerGiftKey.UseDiamonds] = function(cache, diamonds, useDiamonds)
        local config = TriggerGiftTriggerListConfig:getCfgById(cache.triggerId)
        local currTime = os.time()

        --- 在起始时间内
        if not config.startDate or currTime >= config.startDate then
            cache.accumulate = cache.accumulate or 0
            cache.accumulate = cache.accumulate + useDiamonds

            if cache.accumulate >= config.param[1] and cache.accumulate <= config.param[2] then
                return true
            end
        end
        return false
    end,

    [Define.TriggerGiftKey.UseMaxDiamonds] = function(cache, diamonds, useDiamonds)
        local config = TriggerGiftTriggerListConfig:getCfgById(cache.triggerId)
        local currTime = os.time()

        cache.maxDiamonds = cache.maxDiamonds or 0
        cache.maxDiamonds = math.max(cache.maxDiamonds, useDiamonds)

        --- 在起始时间内
        if not config.startDate or currTime >= config.startDate then
            if cache.maxDiamonds >= config.param[1] and cache.maxDiamonds <= config.param[2] then
                return true
            end
        end
        return false
    end,
}

