local function randomItemByWeight(num, pool, ifReduce)
    if type(num) ~= "number"
            or type(pool) ~= "table"
            or type(ifReduce) ~= "boolean" then
        return nil
    end
    local sumOfWeight = getSumOfWeight(pool)
    local result = {}

    local function randomItem()
        if ifReduce then
            sumOfWeight = getSumOfWeight(pool)
        end
        local rs = HostApi.random("RandomPool", 0, sumOfWeight)
        for index, item in pairs(pool) do
            rs = rs - item.weight
            local pItem = item
            if rs < 0 then
                return pItem, index
            end
        end
    end

    for i = 1, num do
        local item, index = randomItem()
        while item == nil do
            item, index = randomItem()
        end
        table.insert(result, item)
        if ifReduce then
            table.remove(pool, index)
        end
    end
    return result
end


