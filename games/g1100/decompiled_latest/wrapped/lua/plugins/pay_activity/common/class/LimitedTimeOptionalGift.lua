    local record = self.info:getValue("OptionalGiftRecord")
    local config = self:getConfig(configId)
    if not config then return end
    local buyTimes = record["buy-times"] or 0
    local limitTimes = record["limit-times"] or 0
    local buyCount = record[config.giftKey] or 0
    if config.type == 1 and config.limitCounts >= 0 and buyCount >= config.limitCounts then
        return
    end

    if config.type == 2 and buyCount >= limitTimes then
        return
    end

    if isClient then
        PayHelper.checkMoney(CurrencyId.GCube, config.price, function(success)
            if success then
                self:runServerFunc("tryBuy", configId, rewardIds)
            end
        end)
    else
        local countdown = self.cfg.endDate - os.time()
        if countdown <= 0 then return end
        if not self:canReward(rewardIds) then
            return
        end

        PayHelper.payMoneySync(self.player, config.id, CurrencyId.GCube, config.price, function()
            if config.type == 1 and config.refreshTime <= 0 then
                record["buy-times"] = buyTimes + 1
                local advancedAward = LimitedTimeOptionalGiftConfig:getAdvancedAward()
                if advancedAward then
                    record["limit-times"] = math.min(math.floor(record["buy-times"] / advancedAward.openCondition), advancedAward.limitCounts)
                end
            end
            --先限制购买次数，失败再回滚
            record[config.giftKey] = buyCount + 1
            if record[config.giftKey] >= config.limitCounts and config.refreshTime > 0 then
                record[config.giftKey .. "-refresh-time"] = self:getRefreshTime(config.refreshTime)
            end
            self.info:setValue("OptionalGiftRecord", record)

            self:doReward(rewardIds, "GUILimitedTimeActivityRewardResult")
            local _record = self.info:getValue("OptionalGiftRecord")
            local _buyCount = (_record[config.giftKey] or 1)
