function LimitedTimeMoonCard:tryBuyCard(cardId)
    local record = self.info:getValue(PayActivityDefine.MoonCardInf.MoonCardRecord)
    if not record  or not cardId then
        return
    end

    local cfg = LimitedTimeMoonCardConfig:getCfgById(cardId)
    if not cfg then
        return
    end

    if self:isCardActive(record[tostring(cfg.giftKey)]) then
        return
    end
    
    if isClient then
        PayHelper.checkMoney(CurrencyId.GCube, cfg.finalPrice, function(success)
            if success then
                self:runServerFunc("tryBuyCard", cardId)
            end
        end)
    else
        if self.buyCtrl[cfg.giftKey] then
            return
        end
        self.buyCtrl[cfg.giftKey]=true
        PayHelper.payMoneySync(self.player, cfg.id, CurrencyId.GCube, cfg.finalPrice, function()
            self.buyCtrl[cfg.giftKey]=false
            self:_setBuyCardRecord(cardId)
            local reward=self:_getReward(cardId)
            if reward then
                self:playerGetGift(reward,nil,cardId)
            end
            ReportEvent.reportEvent(self.player.userId, "monthly_card_buy", false, {
                monthly_card_id = cfg.id,
            })
        end, function ()
            self.buyCtrl[cfg.giftKey]=false
        end , nil, "Activity:" .. self.activityId)
    end
end

