local function onTick()
    local players = PlayerManager:getPlayers()
    for _, player in pairs(players) do
        if player:checkReady() then
            local result = {}
            for activityId, activity in pairs(player.payActivity.activities) do
                if activity.info.change then
                    local toSelf, _ = activity.info:getSyncData()
                    result[activityId] = toSelf
                    activity.info.change = false
                end
            end
            if next(result) ~= nil then
                PayActivityPkSender:syncPayActivityData(player, result)
            end
        end
    end
end

---@private
function PayActivityMgr:init()
    self.activities = {}
    self:onSecondTick()
    LuaTimer:scheduleTimer(function()
        self:onSecondTick()
    end, 1000)
    LuaTimer:scheduleTicker(function()
        onTick()
    end, 1)
end

---@private
function PayActivityMgr:onSecondTick()
    local curTime = os.time()
    local cfgs = PayActivityConfig:getAllCfgs()
    for _, cfg in pairs(cfgs) do
        if curTime >= cfg.startDate and (curTime < cfg.endDate or cfg.endDate < 0) then
            self:tryCreateActivity(cfg.id)
        else
            self:tryRemoveActivity(cfg.id)
        end
    end
    PayActivityConfig:checkResetRoundTime(false)
    local players = PlayerManager:getPlayers()
    for _, player in pairs(players) do
        if player:checkReady() then
            player.payActivity:onSecondTick(curTime)
        end
    end
end

