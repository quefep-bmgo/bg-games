---@public
---@param parent GUIWindow
function GUIRedDotWindow:show(parent, isVisible)
    assert(parent, 'must have parent node')
    self:initView()
    parent:AddChildWindow(self.root)
    if isVisible ~= nil then
        self.root:SetVisible(isVisible)
    end
    if self.key then
        ---纳入红点管理的初始化默认值都是false，由红点管理来操控显示
        self.root:SetVisible(false)
        if not RedDotMgr:isAlreadyRegistered(self.key) then
            ---还没有注册的话现在直接注册一个关系树
            if self.parentKey then
                local parentKey = self.parentKey
                local profile = {
                    [parentKey] = {
                        self.key
                    }
                }
                RedDotMgr:registerProfile(profile)
            else
                RedDotMgr:registerProfile(self.key)
            end
        end
        ---这里不需要管这个key值有没有注册，因为不注册的key值是修改不了的，也就不会调用这里
        RedDotMgr:linkRedDotAction(self.key, function(show)
            self:refresh(show)
        end, self.redDotId)
    end
    if self.isParentBindVisible then
        parent:SetVisible(self.root:IsVisible())
    end
    return self
end

---@public 接收红点数据
function GUIRedDotWindow:refresh(show)
    self.root:SetVisible(show > 0)
    if self.isParentBindVisible then
        self.root:GetParent():SetVisible(self.root:IsVisible())
    end
    if self.isShowNumber then
        self.txtNum:SetText(tostring(show))
    end
end

function GUIRedDotWindow:onDestroy()
    if self.key then
        RedDotMgr:unlinkRedDotAction(self.key, self.redDotId)
    end
end

