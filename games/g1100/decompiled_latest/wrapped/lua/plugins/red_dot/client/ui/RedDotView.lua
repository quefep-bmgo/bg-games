function GUIRedDotWindow:ctor(key, parentKey)
    self.key = key ---红点管理key,不传的话不会被红点系统管理
    self.parentKey = parentKey
    self.defaultRadius = 11
    self.customImage = nil
    self.isShowNumber = false
    self.fontSize = "HT10"
    self.offset = { x = 0, y = 0 }
    self.redDotId = allowId()
    self.windowId = GUIManager:applyWindowId()
    self:init()
end

function GUIRedDotWindow:init()
    self.root = GUIManager:createGUIWindow(GUIType.Layout, 'RedDot' .. self.redDotId)
    self.root:SetArea({ 0, 0 }, { 0, 0 }, { 1, 0 }, { 1, 0 })
    self.root:SetTouchable(false)
    self.root:registerEvent(GUIEvent.WindowDestroy, function()
        self:destroy()
    end)
end

function GUIRedDotWindow:initView()
    local imgRedDot = GUIManager:createGUIWindow(GUIType.StaticImage, 'RedDot-Point' .. self.redDotId)
    imgRedDot:SetTouchable(false)
    imgRedDot:SetProperty("Material", "CullBackLinear")
    imgRedDot:SetHorizontalAlignment(HorizontalAlignment.Right)
    self.root:AddChildWindow(imgRedDot)

    if self.isShowNumber then
        self.txtNum = GUIManager:createGUIWindow(GUIType.StaticText, "RedDot-Num" .. self.redDotId)
        self.txtNum:SetHorizontalAlignment(HorizontalAlignment.Center)
        self.txtNum:SetVerticalAlignment(VerticalAlignment.Center)
        self.txtNum:SetArea({ 0, 0 }, { 0, 0 }, { 1, 0 }, { 1, 0 })
        self.txtNum:SetTextVertAlign(VerticalAlignment.Center)
        self.txtNum:SetTextHorzAlign(HorizontalAlignment.Center)
        self.txtNum:SetProperty("Font", self.fontSize)
        imgRedDot:AddChildWindow(self.txtNum)
    end

    local size
    if self.customImage then
        ---使用自定义图片
        UIHelper:setImageAdjustSize(imgRedDot, self.customImage, 60, 60)
        size = imgRedDot:GetPixelSize()
    else
        local imgUrl = "set:bed_war_3_common_part.json image:img_0_red_dot02" ---22*22
        UIHelper:setImageAdjustSize(imgRedDot, imgUrl, 60, 60)
        size = { x = self.defaultRadius * 2, y = self.defaultRadius * 2 }
    end
    imgRedDot:SetArea({ 0, 0 + self.offset.x }, { 0, 0 + self.offset.y }, { 0, size.x }, { 0, size.y })
end

