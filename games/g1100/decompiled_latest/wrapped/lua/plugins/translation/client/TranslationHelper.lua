local TranslationHelper = T(Global, "TranslationHelper")
---@type ChatClient
local ChatClient = T(Global, "ChatClient")

function TranslationHelper:init()
    self.aiTranslationEnable = ClientHelper.getBoolForKey("AiTranslationEnable", false)
    self:syncTranslationEnable()
end

function TranslationHelper:setTranslationEnable(enable)
    ClientHelper.putBoolForKey("AiTranslationEnable", enable)
    self.aiTranslationEnable = enable
    self:syncTranslationEnable()
end

function TranslationHelper:syncTranslationEnable()
    if ShellInterface.setGameMsgTranslateEnable then
        CGame.Instance():getShellInterface():setGameMsgTranslateEnable(self.aiTranslationEnable)
    end
    local player = PlayerManager:getClientPlayer()
    self:updateTranslationBtnIcon()
    if player then
        player:sendPacket({
            pid = "SyncTranslationEnable",
            enable = self.aiTranslationEnable
        })
    end
end

function TranslationHelper:getTranslationEnable()
    return self.aiTranslationEnable
end

function TranslationHelper:addTranslationBtn(parent, params)
    if self.translationBtn then
        return
    end
    params = params or {}
    self.translationBtn = GUIManager:createGUIWindow(GUIType.Button, "AiTranslation-Enable" .. GUIManager:applyWindowId())
    self:updateTranslationBtnIcon()
    self.translationBtn:SetHorizontalAlignment(HorizontalAlignment.Right)
    self.translationBtn:SetVerticalAlignment(VerticalAlignment.Center)
    self.translationBtn:SetWidth({ 0, 114 })
    self.translationBtn:SetHeight({ 0, 47 })
    self.translationBtn:registerEvent(GUIEvent.ButtonClick, function()
        self:setTranslationEnable(not self.aiTranslationEnable)
    end)
    if params.x then
        self.translationBtn:SetXPosition( { 0, params.x } )
    end
    if params.y then
        self.translationBtn:SetYPosition( { 0, params.y } )
    end
    parent:AddChildWindow(self.translationBtn)
end

function TranslationHelper:updateTranslationBtnIcon()
    if not self.translationBtn then
        return
    end
    local icon = self.aiTranslationEnable and "set:ai_ranslation.json image:btn_icon_translation_off" or "set:ai_ranslation.json image:btn_icon_translation_on"
    self.translationBtn:SetNormalImage(icon)
    self.translationBtn:SetPushedImage(icon)
end

function TranslationHelper:tryTranslate(info)
    local text = info.data.content
    local sendId = info.sendId
    local targetId = info.targetId
    local msgId = info.msgId
    if info.isPrivate then
        local targetUid = sendId == Game:getPlatformUserId() and targetId or sendId
        if ShellInterface.translationMessage then
            CGame.Instance():getShellInterface():translationMessage(tostring(targetUid), tonumber(msgId), text)
        end
    else
        WebService:CTryTranslate(text, function(data, code)
            if code ~= 1 then
                return
            end
            for _, v in pairs(data) do
                for _, s in pairs(v) do
                    info.data.translation = s
                    break
                end
            end
            if ChatClient.updateChatMsgData then
                ChatClient:updateChatMsgData(info)
            end
            Events.UpdateTranslationChatMsg:invoke(info.sendId, info.msgId, info.data)
        end)
    end

end

