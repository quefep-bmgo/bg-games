function BulletinInfo:initListener()
    if isServer then
        return
    end
    self:addKeyObserver(Define.BulletinInfoKey.IsOpenUI, function(_, _, value)
        if value then
            UIHelper.showGameGUILayout("GUIBulletin")
        end
    end)
end

function BulletinInfo:onPlayerReady()
    local cfgs = BulletinConfig:getAllCfgs()
    for _, cfg in pairs(cfgs) do
        local version = self:getValue(Define.BulletinInfoKey.Version .. cfg.id)
        if version < cfg.version then
            self:setValue(Define.BulletinInfoKey.Version .. cfg.id, cfg.version)
            self:setValue(Define.BulletinInfoKey.IsOpenUI, true)
        end
    end
end

