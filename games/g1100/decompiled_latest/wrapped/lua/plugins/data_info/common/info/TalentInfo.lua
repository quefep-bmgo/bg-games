function TalentInfo:onTalentChange(id, level)
    if isClient then
        return
    end
    local cfg = AchieveTalentConfig:getCfgById(id)
    if not cfg then
        return
    end
    local old = self.records[cfg.id]
    if old then
        if cfg.type == Define.AchieveTalentType.Attr then
            self.player.attr:decValue(cfg.values[1], old)
        elseif cfg.type == Define.AchieveTalentType.Buff then
            self.player.buff:removeBuffTrigger(old)
        end
        self.records[cfg.id] = nil
    end
    if level <= 0 then
        return
    end
    level = math.min(level, cfg.maxLv)
    if cfg.type == Define.AchieveTalentType.Attr then
        local value = tonumber(cfg.values[2]) * level
        self.player.attr:incValue(cfg.values[1], value)
        self.records[cfg.id] = value
    elseif cfg.type == Define.AchieveTalentType.Buff then
        local buffId = tonumber(cfg.values[level] or cfg.values[1])
        self.player.buff:createBuffTrigger(buffId)
        self.records[cfg.id] = buffId
    end
