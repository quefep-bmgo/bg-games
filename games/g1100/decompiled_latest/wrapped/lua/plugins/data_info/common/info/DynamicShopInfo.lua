function DynamicShopInfo:tryBuyGoods(player, id, price)
    if self:getBoolValue(Define.DynamicShopInfoKey.Updating) then
        if isClient then
            UIHelper.showToast(Lang:getString("gui.dynamic.shop.updating"))
        end
        return
    end
    local cfg = DynamicShopConfig:getGoodsById(id)
    if not cfg or not self:isGoodsShow(id) then
        return
    end
    local rewards = { { cfg.reward.id, cfg.rewardCount } }
    if not RewardUtil:canRewards(player, rewards) then
        return
    end
    if isClient then
        price = self:getBuyPrice(id)
        PayHelper.checkMoney(cfg.priceType, price, function(success)
            if success then
                CustomDialog.builder()
                            .setContentText(Lang:format("gui_cost_much_money_tip", cfg.rewardCount, RewardConfig:getRewardName(cfg.reward)))
                            .setCurrencyInfo(cfg.priceType, price)
                            .setRightClickListener(function()
                    DynamicShopPkSender:tryBuyDynamicShopItem(id, price)
                end)        .show()
            end
        end)
    else
        if self:getBuyPrice(id) ~= price then
            return
        end
        PayHelper.payMoneySync(player, id, cfg.priceType, price, function()
            RewardUtil:doRewards(player, rewards)
            CustomInfoUtil:incCustomValue(DynamicShopUID, "dynamic_shop_goods_buy_" .. id, 1)
        end, nil, nil, "DynamicShop")
    end
end

