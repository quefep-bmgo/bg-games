    local cfgs = DynamicShopConfig:getAllCfgs()
    local keys = {}
    for _, cfg in pairs(cfgs) do
        table.insert(keys, "dynamic_shop_goods_buy_" .. cfg.id)
        table.insert(keys, "dynamic_shop_goods_sell_" .. cfg.id)
    end
    LuaTimer:cancel(self.timer)
    local old = UserInfoCache:GetCache(DynamicShopUID)
    if old then
        for _, key in pairs(keys) do
            old[key] = nil
        end
    end
    self:setValue(Define.DynamicShopInfoKey.Updating, true)
    CustomInfoUtil:getCustomValue(DynamicShopUID, keys, function(info)
        self:setValue(Define.DynamicShopInfoKey.Updating, false)
        self:setValue(Define.DynamicShopInfoKey.RefreshTime, os.time())
        self.timer = LuaTimer:schedule(function()
            self:updatePrice()
        end, Define.DynamicShopRefreshTime * 1000)
        if not info then
            return
        end
        for _, cfg in pairs(cfgs) do
            local time1 = info["dynamic_shop_goods_buy_" .. cfg.id] or 0
            local time2 = info["dynamic_shop_goods_sell_" .. cfg.id] or 0
            local price1 = cfg.defBuyPrice * (1 + time1 * cfg.incBuyPriceX - time2 * cfg.decBuyPriceX)
            local price2 = cfg.defSellPrice * (1 + time1 * cfg.incSellPriceX - time2 * cfg.decSellPriceX)
            price1 = math.max(math.min(cfg.maxBuyPrice, price1), cfg.minBuyPrice)
            price2 = math.max(math.min(cfg.maxSellPrice, price2), cfg.minSellPrice)
            self:setValue(Define.DynamicShopInfoKey.BuyPrice .. cfg.id, math.ceil(price1))
            self:setValue(Define.DynamicShopInfoKey.SellPrice .. cfg.id, math.ceil(price2))
        end
    end)
