function DynamicShopInfo:trySellGoods(player, id, price)
    if self:getBoolValue(Define.DynamicShopInfoKey.Updating) then
        if isClient then
            UIHelper.showToast(Lang:getString("gui.dynamic.shop.updating"))
        end
        return
    end
    local cfg = DynamicShopConfig:getGoodsById(id)
    if not cfg or not self:isGoodsShow(id) then
        return
    end
    if not DynamicShopConfig:isGoodsCanSell(cfg) then
        return
    end
    local inventory = player:getPlayerInventory()
    local itemId, meta = cfg.reward.realId, cfg.reward.extraId
    local count = inventory:getItemCount(itemId, meta)
    if count < cfg.rewardCount then
        if isClient then
            CustomDialog.builder()
                        .setContentText(Lang:getString("gui.no.such.item.tip"))
                        .setHideLeftButton()
                        .show()
        end
        return
    end
    if isClient then
        price = self:getSellPrice(id)
        CustomDialog.builder()
                    .setContentText(Lang:format("gui.dynamic.shop.sell.tip", RewardConfig:getRewardName(cfg.reward)))
                    .setCurrencyInfo(cfg.priceType, price)
                    .setRightClickListener(function()
            DynamicShopPkSender:trySellDynamicShopItem(id, price)
        end)        .show()
    else
        if self:getSellPrice(id) ~= price then
            return
        end
        inventory:tryRemoveItem(itemId, meta, cfg.rewardCount)
        inventory:reportItemChange(itemId, meta, -cfg.rewardCount)
        local rewardId
        if cfg.priceType == CurrencyId.Currency then
            player:addCurrency(price, "DynamicShop")
            rewardId = 12001
        elseif cfg.priceType == CurrencyId.PassScore then
            player.pass:addPassScore(price, "DynamicShop", cfg.id)
            rewardId = 14001
        elseif cfg.priceType == CurrencyId.TaskChainScore then
            player.task_chain:addScore(price, "DynamicShop", cfg.id)
            rewardId = 15001
        end
        if rewardId then
            RewardUtil:addRewardRecord(player, rewardId, price)
        end
        CustomInfoUtil:incCustomValue(DynamicShopUID, "dynamic_shop_goods_sell_" .. id, 1)
    end
end

