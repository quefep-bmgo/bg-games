        if inventory.backpack.key == key then
            local item = inventory.backpack.slots[index]
            if itemId == item.itemId and meta == item.meta and item.count >= count then
                item:updateCount(-count)
            else
                inventory:tryRemoveItem(itemId, meta, count)
            end
        else
            local item = inventory.hotbar.slots[index]
            if itemId == item.itemId and meta == item.meta and item.count >= count then
                item:updateCount(-count)
            else
                inventory:tryRemoveItem(itemId, meta, count)
            end
        end
        inventory:reportItemChange(itemId, meta, -count, "Trade", targetId)
        hasCollectProp = hasCollectProp or RankConfig:isCurCollectProp(itemId)
        LogUtil.logInfo("[Trade][ItemContainer:removeSlots][" .. player.userId .. "]" .. "[" .. targetId .. "]", key, index, StringUtil.a2s({ itemId, meta, -count }))
    end
