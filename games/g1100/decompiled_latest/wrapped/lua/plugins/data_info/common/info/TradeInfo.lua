function TradeInfo:saveHistory(record)
    if record.self.currency ~= 0
            or #record.self.slots ~= 0
            or #record.self.pets ~= 0
            or record.target.currency ~= 0
            or #record.target.slots ~= 0
            or #record.target.pets ~= 0
    then
        local records = self:getValue(Define.TradeInfoKey.History)
        while #records >= 3 do
            table.remove(records, #records)
        end
        record.updateTime = os.time()
        for _, slot in pairs(record.self.slots) do
            slot[4] = nil
            slot[5] = nil
        end
        for _, slot in pairs(record.target.slots) do
            slot[4] = nil
            slot[5] = nil
        end
        for _, pet in pairs(record.self.pets) do
            pet[Define.PetInfoKey.UpdateTime] = nil
        end
        for _, pet in pairs(record.target.pets) do
            pet[Define.PetInfoKey.UpdateTime] = nil
