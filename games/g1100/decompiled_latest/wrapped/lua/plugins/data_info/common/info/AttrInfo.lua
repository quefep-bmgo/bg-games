function AttrInfo:checkMaxHealthChange()
    if not self.isMaxHpChange then
        return
    end
    self.isMaxHpChange = false
    local oldMaxHp = self.player:getMaxHealth()
    local newMaxHp = math.max(Define.InitHP, self:getValue(Define.AttrInfoKey.MaxHealth))
    if oldMaxHp == newMaxHp then
        return
    end
    local health = self.player:getHealth()
    self.player:changeMaxHealth(newMaxHp, true)
    self.player:setHealth(math.min(health, newMaxHp))
    self.player.buff:trigger("onAttrChange", Define.AttrInfoKey.MaxHealth, newMaxHp)
end

function AttrInfo:checkAutoBloodValue()
    self.waitAutoBlood = self.waitAutoBlood + 100
    if self.waitAutoBlood >= 4000 then
        local value = self:getValue(Define.AttrInfoKey.AutoBloodValue)
        if value > 0 then
            local curHp = self.player:getHealth()
            local maxHp = self.player:getMaxHealth()
            if curHp < maxHp then
                self.player:addHealth(value)
            end
        elseif value < 0 then
            self.player:addHealth(value)
        end
        self.waitAutoBlood = 0
    end
end

