function ProductInfo:upgradeProduct(productId)
    local level = self:getProduct(productId)
    if level == 0 then
        return
    end
    local cfg = ProductConfig:getCfgById(productId)
    if not cfg then
        return
    end
    local nextLv = level + 1
    if not cfg.levelList[nextLv] then
        return
    end
    self:setValue(tostring(productId), nextLv)
    local mineField = MineFieldMgr:getMineField(self.player.userId)
    if mineField then
        mineField:updateMineMachine(productId, nextLv)
        mineField:getMinePool():updateContainerSize()
    end
    self:reportProductChange(nextLv, productId)
    TaskUtil:upgradeProduct(self.player, productId, nextLv)
end

---售卖所有资源产物
function ProductInfo:trySellAllProduct()
    local mineField = MineFieldMgr:getMineField(self.player.userId)
    if not mineField then
        return
    end
    local currency = 0
    local minePool = mineField:getMinePool()
    for _, slot in pairs(minePool.container.slots) do
        if slot.itemId > 0 then
            local money = ItemInfoConfig:getItemMoney(slot.itemId)
            currency = currency + money * slot.count
        end
    end
    minePool:clearAllItem()
    if currency == 0 then
        return
    end
    self.player:addCurrency(currency, "SellAllProduct")
    TaskUtil:sellProduct(self.player, currency)
end

