function ProductInfo:unlockProduct(productId)
    if self:hasProduct(productId) then
        return false
    end
    self:setValue(tostring(productId), 1)
    local mineField = MineFieldMgr:getMineField(self.player.userId)
    if mineField then
        local machine = mineField:updateMineMachine(productId, 1)
        mineField:getMinePool():updateContainerSize()
        if machine then
            machine:forceOutput()
        end
    end
    self:reportProductChange(1, productId)
    TaskUtil:upgradeProduct(self.player, productId, 1)
    return true
end

