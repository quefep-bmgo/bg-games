function AchieveInfo:checkNewRewards()
    local oldScore = self:getValue(Define.AchieveInfoKey.OldScore)
    local newScore = self:getValue(Define.AchieveInfoKey.Score)
    local cfgs = AchieveRewardConfig:getCfgsByScoreRange(oldScore, newScore)
    if next(cfgs) ~= nil then
        local rewards = self:getValue(Define.AchieveInfoKey.Rewards)
        for _, cfg in pairs(cfgs) do
            table.insert(rewards, cfg.id)
        end
        self:setValue(Define.AchieveInfoKey.Rewards, rewards)
    end
    self:setValue(Define.AchieveInfoKey.OldScore, newScore)
end

