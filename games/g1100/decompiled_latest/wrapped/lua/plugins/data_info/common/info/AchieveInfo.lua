function AchieveInfo:initAchieveTask(player)
    tryAddAchieveTask(player, "achieve_child")
    local tasks = AchieveConfig.config.tasks
    for _, task in pairs(tasks) do
        if task.key then
            tryAddAchieveTask(player, task.key)
        end
        for _, child in pairs(task.child or {}) do
            if child.key then
                tryAddAchieveTask(player, child.key)
            end
        end
    end
end

