function AchieveInfo:tryReceiveReward(player, id)
    local rewards = self:getValue(Define.AchieveInfoKey.Rewards)
    if not TableUtil.tableContain(rewards, id) then
        return
    end
    local cfg = AchieveRewardConfig:getCfgById(id)
    if not cfg then
        return
    end
    local reward = { { cfg.rewardId, cfg.rewardCount } }
    if not RewardUtil:canRewards(player, reward) then
        return
    end
    if isClient then
        AchievePkSender:tryReceiveAchieveReward(id)
    else
        RewardUtil:doRewards(player, reward)
    end
