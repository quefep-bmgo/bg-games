---@param player SBasePlayer
function handlers.onSavePlayerDBData(player, immediate)
    player.info:onSaveDBData(player)
    local data = {}
    local match = player.userId .. ":"
    local infos = DataInfoMgr:findDataInfo(match)
    for name, info in pairs(infos) do
        local type = string.gsub(name, match, "")
        data[type] = info:getSaveDBData()
    end
    if TableUtil.isEmpty(data) then
        local format = "[data_info] onSavePlayerDBData failed, data is empty. userId=%s, immediate=%s"
        LogUtil.logScriptException(string.format(format, player.userId, tostring(immediate)))
    else
        DBManager:savePlayerData(player.userId, DataInfoKey, data, immediate)
    end
end

