local ErrorLogIds = T(Global, "ErrorLogIds")

CEvents.ScriptErrorEvent:registerCallBack(function(scriptError)
    local isErrorLog = isStaging or isTest
    if isClient then
        isErrorLog = isErrorLog or TableUtil.tableContain(ErrorLogIds, Game:getPlatformUserId())
        if not isErrorLog then
            return
        end
        if not CustomDialog or not CustomDialog.isLoad() then
            LuaTimer:schedule(function()
                CEvents.ScriptErrorEvent:invoke(scriptError)
            end, 1000)
            return
        end
        local width, height = 1080, 600
        if GUISystem.Instance():GetScreenHeight() > GUISystem.Instance():GetScreenWidth() then
            width = 600
            height = 1080
        end
        CustomDialog.builder()
                    .setTitleText("客户端脚本报错，截图发群")
                    .setPanelSize(width, height)
                    .setContentAlign(HorizontalAlignment.Left)
                    .setContentText(scriptError)
                    .setHideLeftButton()
                    .setDisableTime(3)
                    .setRightText("复制到粘贴板")
                    .setRightClickListener(function()
            ClientHelper.onSetClipboard(scriptError)
            UIHelper.showToast("复制成功，请发送到群里")
        end)
                    .show()
    else
        if isErrorLog then
            PacketSender:broadCastLuaCommonData("ScriptError", scriptError)
        else
            local players = PlayerManager:getPlayers()
            for _, player in pairs(players) do
                if TableUtil.tableContain(ErrorLogIds, player.userId) then
                    PacketSender:sendLuaCommonData(player.rakssid, "ScriptError", scriptError)
                end
            end
        end
    end
end)

