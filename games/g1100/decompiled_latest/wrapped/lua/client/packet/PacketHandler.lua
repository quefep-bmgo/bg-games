function PacketHandlers:setSleep(packet)
    local playerId = packet.playerId
    local player = PlayerManager:getPlayerByUserId(playerId)
    if player and player.Player then
        player.Player:setFlying(false)
        if packet.yaw then
            player.Player.rotationYaw = packet.yaw
            player.Player.renderYawOffset = packet.yaw
        end
        if packet.pos then
            player.sleepPos = packet.pos
            local y = playerId == Game:getPlatformUserId() and packet.pos.y + Define.EyeOffsetFromFoot + 0.1 or packet.pos.y + 0.1
            player.Player:setPosition(VectorUtil.newVector3(packet.pos.x, y, packet.pos.z))
        end
        player.isSleeping = true
        player:setBaseAction("sleep1")
        player:setUpperAction("sleep1")
        LuaTimer:schedule(function(userId)
            local _player = PlayerManager:getPlayerByUserId(userId)
            if _player and _player.Player and _player.isSleeping then
                if playerId == Game:getPlatformUserId() then
                    _player.Player:setCameraLocked(true)
                end
                _player.isCameraLocked = true
            end
        end, 300, nil, player.userId)
        if playerId == Game:getPlatformUserId() then
            Blockman.Instance():setPersonView(1)
        end
        if packet.yaw then
            LuaTimer:scheduleTicker(function()
                player.Player.rotationYaw = packet.yaw
                player.Player.renderYawOffset = packet.yaw
            end, 5, 1)
        end
    end
end

